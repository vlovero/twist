static int global_argc;
static char **global_argv;

int get_number_of_groups(H5::H5File &file);

void set_program_args(int argc, char **argv)
{
    global_argc = argc;
    global_argv = argv;
}

std::string get_program_argv()
{
    return fmt::format("{}", fmt::join(std::vector<std::string_view>(global_argv, global_argv + global_argc), " "));
}

char **get_program_raw_argv()
{
    return global_argv;
}

static herr_t count_numeric_cb(hid_t, const char *name, const H5L_info_t *, void *op_data)
{
    if (name && name[0] != '\0') {
        bool all_digits = true;
        for (const char *p = name; *p != '\0'; ++p) {
            if (!std::isdigit(static_cast<unsigned char>(*p))) {
                all_digits = false;
                break;
            }
        }
        if (all_digits) {
            (*static_cast<int *>(op_data))++;
        }
    }
    return 0;
}

static herr_t collect_names_cb(hid_t, const char *name, const H5L_info_t *, void *op_data)
{
    if (name && name[0] != '\0') {
        static_cast<std::vector<std::string> *>(op_data)->emplace_back(name);
    }
    return 0;
}

int get_number_of_solutions(const H5::Group &group)
{
    int count = 0;
    H5Literate(group.getId(), H5_INDEX_NAME, H5_ITER_INC, NULL, count_numeric_cb, &count);
    return count;
}

std::vector<std::string> get_hopf_branch_names(H5::H5File &h5_file)
{
    std::vector<std::string> names;
    if (!h5_file.nameExists("hopf_branches")) {
        return names;
    }
    H5::Group hb = h5_file.openGroup("hopf_branches");
    H5Literate(hb.getId(), H5_INDEX_NAME, H5_ITER_INC, NULL, collect_names_cb, &names);
    std::sort(names.begin(), names.end());
    return names;
}

int get_number_of_solutions(const std::string &path)
{
    H5::H5File h5_file(path, H5F_ACC_RDONLY);
    return get_number_of_solutions(h5_file);
}

herr_t op_func(hid_t, const char *, const H5L_info_t *, void *op_data)
{
    int *idata = (int *)op_data;
    // puts(name);
    idata[0] += 1;
    return 0;
}

int get_number_of_groups(H5::H5File &file)
{
    int group_count = 0;
    H5Literate(file.getId(), H5_INDEX_NAME, H5_ITER_INC, NULL, op_func, &group_count);
    return group_count;
}

int get_number_of_solutions(H5::H5File &h5_file)
{
    TWIST::FileType file_type;
    int ngroups = get_number_of_groups(h5_file);

    if (!h5_file.exists("meta_data")) {
        throw std::runtime_error(fmt::format("meta_data is not present. {} was likely not generated by twist continuation or was corrupted.", h5_file.getFileName()));
    }

    H5::Group group{ h5_file.openGroup("meta_data") };
    deserialize(group, "file_type", file_type);

    switch (file_type) {
    case TWIST::FileType::continuation:
    case TWIST::FileType::hopf_continuation: {
        H5::Group root = h5_file.openGroup("/");
        ngroups = get_number_of_solutions(root);
        break;
    }
    case TWIST::FileType::spectrum:
        ngroups -= 1;
        break;
    case TWIST::FileType::bifurcation_points:
        ngroups -= 2;
        break;
    case TWIST::FileType::preprocess:
        ngroups = 1;
        break;
    default:
        break;
    }

    return ngroups;
}